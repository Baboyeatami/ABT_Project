import { test, expect } from '@playwright/test'

test('owner overview, demo insights and mobile navigation', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/login')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A good day starts here.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Room overview' })).toBeVisible()
  await page.getByRole('button', { name: 'Show sample insights' }).click()
  await expect(page.getByText('Sample insights · Rule-based demo, not generated by AI')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Your next steps' })).toBeVisible()
  await page.getByLabel('AI reporting period').selectOption('30')
  await expect(page.getByRole('heading', { name: 'Your next steps' })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/owner-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).not.toBeVisible()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Open navigation' })).toBeFocused()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Front desk', exact: true }).click()
  await expect(page).toHaveURL(/reservations/)
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).not.toBeVisible()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A good day starts here.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/owner-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})

test('instructor can open hotel insights; kitchen staff see only their modules', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: /instructor@abt.demo/ }).click()
  await page.getByRole('link', { name: 'Open administration' }).click()
  await page.getByRole('button', { name: 'Performance', exact: true }).click()
  await page.locator('tbody tr[role="button"]').first().click()
  await page.getByRole('button', { name: 'Show sample insights' }).click()
  await expect(page.getByRole('heading', { name: 'Your next steps' })).toBeVisible()
  await page.locator('.modal-header .btn-close').click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByRole('button', { name: /kitchen@abt.demo/ }).click()
  await expect(page.getByRole('heading', { name: 'Keep things moving' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Show sample insights' })).toHaveCount(0)
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav.getByRole('link', { name: 'Kitchen', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Billing', exact: true })).toHaveCount(0)
})
